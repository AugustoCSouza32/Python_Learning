x = 5
y = 2

a = x + y #Adição
print(a)

b = x - y #Subtração
print(b)

c = x * y #Multiplicação
print(c)

d = x / y #Divisão
print(d)

e = x // y #Divisão Inteira
print(e)

f = x % y #Módulo
print(f)

g = x ** y #Exponenciação
print(g)

#Operadores de Comparação
print(x == y) #Igualdade
print(x != y) #Diferença
print(x > y) #Maior que
print(x < y) #Menor que
print(x >= y) #Maior ou igual a
print(x <= y) #Menor ou igual a

#Operadores Lógicos
x = True
y = False
print(x and y) #E
print(x or y) #OU
print(not x) #NÃO   

